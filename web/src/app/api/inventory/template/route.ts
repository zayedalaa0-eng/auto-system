import * as XLSX from "xlsx";
import { NextResponse } from "next/server";

import { createClient } from "@/lib/supabase/server";

/**
 * GET /api/inventory/template
 * يُرجع ملف Excel جاهز كـ template للرفع
 */
export async function GET() {
  const supabase = await createClient();
  const { data: { session } } = await supabase.auth.getSession();
  if (!session) {
    return NextResponse.json({ error: "غير مصرح" }, { status: 401 });
  }

  // ── بيانات توضيحية (صف مثال) ───────────────────────────────
  const example = [
    {
      "اسم السيارة / الموديل *": "تويوتا كامري",
      "سنة الصنع *": 2022,
      "اللون *": "أبيض",
      "رقم الشاصي *": "1HGBH41JXMN109186",
      "السعر (شيكل)": 85000,
      "العداد (كم)": 45000,
      "ناقل الحركة": "أوتوماتيك",
      "نوع الوقود": "بنزين",
      "حالة السيارة": "مستعملة",
      "نوع الصفقة": "شراء",
      "حالة التوفر": "متوفرة",
      "مواصفات إضافية": "فتحة سقف، كاميرا خلفية",
      "ملاحظات الفحص": "فحص كامل - لا يوجد حوادث",
    },
  ];

  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.json_to_sheet(example);

  // ── تحديد عرض الأعمدة ──────────────────────────────────────
  ws["!cols"] = [
    { wch: 28 }, // اسم السيارة
    { wch: 14 }, // سنة الصنع
    { wch: 14 }, // اللون
    { wch: 22 }, // رقم الشاصي
    { wch: 16 }, // السعر
    { wch: 14 }, // العداد
    { wch: 16 }, // ناقل الحركة
    { wch: 14 }, // نوع الوقود
    { wch: 14 }, // حالة السيارة
    { wch: 14 }, // نوع الصفقة
    { wch: 14 }, // حالة التوفر
    { wch: 28 }, // مواصفات
    { wch: 28 }, // ملاحظات الفحص
  ];

  // ── ورقة التعليمات ──────────────────────────────────────────
  const instructions = [
    ["📋 تعليمات ملء ملف استيراد المخزون"],
    ["⚠️ هذا الملف مخصص فقط لسيارات المعرض — وليس لسيارات الأشخاص أو العملاء"],
    [""],
    ["الحقول الإلزامية (*):", "اسم السيارة — سنة الصنع — اللون — رقم الشاصي"],
    ["🏢 اسم المعرض:", "يُملأ تلقائياً من حسابك عند الرفع — لا حاجة لكتابته في الملف"],
    [""],
    ["ناقل الحركة (اختر):", "أوتوماتيك | يدوي | CVT"],
    ["نوع الوقود (اختر):", "بنزين | ديزل | هجين | كهربائي | غاز"],
    ["حالة السيارة (اختر):", "جديدة | مستعملة | بحادث | مصبوغة جزئياً"],
    ["نوع الصفقة (اختر):", "شراء | استبدال | بيع بالوكالة | شراء من عميل"],
    ["", "شراء = المعرض اشترى السيارة مباشرة"],
    ["", "استبدال = جاءت كاستبدال من عميل"],
    ["", "بيع بالوكالة = صاحبها يبيعها عبر المعرض"],
    ["", "شراء من عميل = اشترى المعرض من عميل"],
    ["حالة التوفر (اختر):", "متوفرة | محجوزة | مباعة | مسحوبة من المعرض"],
    [""],
    ["⚠️ ملاحظات مهمة:"],
    ["• لا تغير أسماء الأعمدة في الصف الأول"],
    ["• السعر والعداد بالأرقام فقط بدون رموز أو فواصل"],
    ["• رقم الشاصي إلزامي وفريد — إذا كان موجوداً في النظام سيتم تحديث السيارة بدلاً من إضافتها"],
    ["• يمكنك إضافة عدة سيارات في الورقة الأولى (Data)"],
    ["• اسم المعرض يُحدَّد تلقائياً من النظام — مدير المعرض يُسجَّل اسم معرضه، والمدير العام يختار المعرض"],
  ];

  const wsInstructions = XLSX.utils.aoa_to_sheet(instructions);
  wsInstructions["!cols"] = [{ wch: 30 }, { wch: 55 }];

  XLSX.utils.book_append_sheet(wb, ws, "Data");
  XLSX.utils.book_append_sheet(wb, wsInstructions, "التعليمات");

  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" });

  return new NextResponse(buffer, {
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      "Content-Disposition": 'attachment; filename="inventory-template.xlsx"',
    },
  });
}
