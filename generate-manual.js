const RTL = { rightToLeft: true };
const FONT = "Arial";

function bdr(color = "D5D5D5") {
  const s = { style: BorderStyle.SINGLE, size: 1, color };
  return { top: s, bottom: s, left: s, right: s };
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 360, after: 180 },
    children: [new TextRun({ text, bold: true, size: 36, color: "1E3A5F", font: FONT, rightToLeft: true })],
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 280, after: 140 },
    children: [new TextRun({ text, bold: true, size: 28, color: "2563EB", font: FONT, rightToLeft: true })],
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 200, after: 100 },
    children: [new TextRun({ text, bold: true, size: 24, color: "1D4ED8", font: FONT, rightToLeft: true })],
  });
}

function p(text, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 80, after: 80 },
    children: [new TextRun({ text, size: 22, font: FONT, rightToLeft: true, ...opts })],
  });
}

function bold(text) {
  return p(text, { bold: true });
}

function note(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 100, after: 100 },
    border: { right: { style: BorderStyle.SINGLE, size: 6, color: "F59E0B" } },
    indent: { right: 200 },
    children: [new TextRun({ text: "⚠️  " + text, size: 22, font: FONT, color: "92400E", rightToLeft: true })],
  });
}

function tip(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { before: 100, after: 100 },
    border: { right: { style: BorderStyle.SINGLE, size: 6, color: "10B981" } },
    indent: { right: 200 },
    children: [new TextRun({ text: "✅  " + text, size: 22, font: FONT, color: "065F46", rightToLeft: true })],
  });
}

function bullet(text, level = 0) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    numbering: { reference: "bullets", level },
    spacing: { before: 60, after: 60 },
    children: [new TextRun({ text, size: 22, font: FONT, rightToLeft: true })],
  });
}

function num(text, level = 0) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    numbering: { reference: "numbers", level },
    spacing: { before: 60, after: 60 },
    children: [new TextRun({ text, size: 22, font: FONT, rightToLeft: true })],
  });
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

function spacer(lines = 1) {
  return new Paragraph({ spacing: { before: 0, after: lines * 100 }, children: [new TextRun("")] });
}

function infoTable(rows) {
  // rows = [[label, value], ...]
  const CW = [3600, 5760];
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    columnWidths: CW,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    rows: rows.map(([label, value], i) =>
      new TableRow({
        children: [
          new TableCell({
            width: { size: CW[0], type: WidthType.DXA },
            borders: bdr(),
            shading: { fill: i % 2 === 0 ? "EFF6FF" : "F8FAFC", type: ShadingType.CLEAR },
            margins: { top: 80, bottom: 80, left: 120, right: 120 },
            children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT,
              children: [new TextRun({ text: label, bold: true, size: 20, font: FONT, rightToLeft: true })] })],
          }),
          new TableCell({
            width: { size: CW[1], type: WidthType.DXA },
            borders: bdr(),
            shading: { fill: i % 2 === 0 ? "FFFFFF" : "F8FAFC", type: ShadingType.CLEAR },
            margins: { top: 80, bottom: 80, left: 120, right: 120 },
            children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT,
              children: [new TextRun({ text: value, size: 20, font: FONT, rightToLeft: true })] })],
          }),
        ],
      })
    ),
  });
}

function twoColTable(headers, rows) {
  const CW = [4680, 4680];
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) =>
      new TableCell({
        width: { size: CW[i], type: WidthType.DXA },
        borders: bdr("2563EB"),
        shading: { fill: "1E3A5F", type: ShadingType.CLEAR },
        margins: { top: 80, bottom: 80, left: 120, right: 120 },
        children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT,
          children: [new TextRun({ text: h, bold: true, size: 20, color: "FFFFFF", font: FONT, rightToLeft: true })] })],
      })
    ),
  });
  const dataRows = rows.map((row, ri) =>
    new TableRow({
      children: row.map((cell, ci) =>
        new TableCell({
          width: { size: CW[ci], type: WidthType.DXA },
          borders: bdr(),
          shading: { fill: ri % 2 === 0 ? "FFFFFF" : "F1F5F9", type: ShadingType.CLEAR },
          margins: { top: 80, bottom: 80, left: 120, right: 120 },
          children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT,
            children: [new TextRun({ text: cell, size: 20, font: FONT, rightToLeft: true })] })],
        })
      ),
    })
  );
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    columnWidths: CW,
    rows: [headerRow, ...dataRows],
  });
}

